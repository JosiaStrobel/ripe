import { describe, expect, it } from 'vitest';
import { parse_todo_lines } from '../parser/todo';
import { parse_shopping } from '../shopping/parser';
import { render_format_export, type FormatExportContext } from './format_export';

const CTX: FormatExportContext = { todo_file: 'Listen/Todos.md', shopping_file: 'Einkaufen.md', default_importance: 2 };

/** Contents of the fenced code blocks in order. */
function code_blocks(text: string): string[] {
	return [...text.matchAll(/```markdown\n([\s\S]*?)```/g)].map((match) => match[1] ?? '');
}

describe('render_format_export', () => {
	const output = render_format_export(CTX);

	it('names the files and says not to edit', () => {
		expect(output.startsWith('# Ripe file formats\n')).toBe(true);
		expect(output).toContain('Do not edit this file');
		expect(output).toContain('## Tasks: `Listen/Todos.md`');
		expect(output).toContain('## Shopping list: `Einkaufen.md`');
	});

	it('shows example task lines the parser accepts without errors', () => {
		const entries = parse_todo_lines(code_blocks(output)[0] ?? '', { default_importance: 2 });
		expect(entries).toHaveLength(6);
		expect(entries.flatMap((entry) => entry.todo.errors)).toEqual([]);
		expect(entries.map((entry) => entry.todo.timing.kind)).toEqual([
			'interval', 'calendar', 'deadline', 'aging', 'none', 'deadline',
		]);
	});

	it('shows an example shopping list the parser reads', () => {
		const categories = parse_shopping(code_blocks(output)[1] ?? '');
		expect(categories.flatMap((c) => c.items.map((item) => item.state))).toEqual(['catalog', 'listed', 'checked']);
	});

	it('depends only on the settings and uses \\n line endings', () => {
		expect(render_format_export(CTX)).toBe(output);
		expect(output).not.toContain('\r');
		expect(render_format_export({ ...CTX, default_importance: 3 })).toContain('default 3');
	});
});
